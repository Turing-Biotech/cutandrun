#!/usr/bin/env python3
"""Post-rewrite the Peak QC child section titles and descriptions in a
Simplified-Chinese MultiQC report (nf-core/cutandrun fork, zh_CN layer).

Why this script exists:
    MultiQC 1.19 exposes no config override point for child subsections that
    carry a parent_id (see docs/multiqc_zh_CN.md, "保持英文" section): the
    assembly pass merges config only by parent_id, and the Peak QC sections
    (primary_peak_counts, consensus_peak_counts, primary_frip_score,
    peak_reprod_perc) all share parent_id 'peak_qc'. The English titles and
    descriptions therefore come from assets/multiqc/*header.txt, which are
    upstream-tracked files we do not modify (editing them would also
    Chinese-ify the English report). This script applies the fixed Chinese
    strings to the rendered HTML instead — the English report is untouched.

Required vs optional entries:
    REQUIRED (Sample/Consensus Peak Count titles + their shared description)
    exist in every finished pipeline render because their data face is the
    published peak beds (peak_counts.nf, cat bed | wc -l). Their absence means
    the report layout changed → fail loud (exit 1), write nothing.
    OPTIONAL (FRiP score, peak reproducibility title + descriptions) come from
    work-only custom_content inputs (*_mqc.tsv) that may have been cleaned from
    the run work directory. Absence is reported as "absent" and skipped —
    the report still gets every Peak QC section the data face actually has.

Usage:
    python3 scripts/multiqc_zh_titles.py <path/to/multiqc_report.html> [--dry-run]

The script refuses to run on a report that is not the zh_CN variant (it checks
for the Chinese report title), rewrites in place, and exits non-zero if any
required English string is missing. Standard library only.
"""

import argparse
import sys

# Anchor that marks the report as the zh_CN variant (assets/multiqc_config_zh_CN.yml
# `title:` value). If it is absent, this is not our report — refuse.
ZH_MARKER = "CUT&RUN/CUT&TAG 质控报告（MultiQC 简体中文版）"

# Fixed replacement pairs. Verbatim strings pinned in
# assets/zh_CN/glossary.yml (report_strings.peak_qc_children); keep in sync.
# Each section title occurs twice in the report (side-nav link + h3 heading).
# The Peak Count description is shared by both Peak Count sections (2 hits).

REQUIRED = [
    # Section titles.
    ("Sample Peak Count", "样本 Peak 数量（Sample Peak Count）"),
    ("Consensus Peak Count", "共识 Peak 数量（Consensus Peak Count）"),
    # Section description (shared, appears once per Peak Count section).
    (
        "Calculated from the total number of peaks called by MACS2 or SEACR",
        "由 MACS2 或 SEACR 所调用的 peak 总数计算得到。",
    ),
]

OPTIONAL = [
    # Section titles (work-only custom_content; may be absent).
    ("Sample FRiP score", "样本 FRiP 得分（FRiP score）"),
    ("Sample Peak reproducibility %", "样本 Peak 可重复性（reproducibility）%"),
    # Section descriptions.
    (
        "is generated by calculating the fraction of all mapped fragments that fall into the peak regions called by either MACS2 or SEACR. See <a href='https://www.encodeproject.org/data-standards/terms/' target='_blank'>FRiP score</a>.",
        "由落在 MACS2 或 SEACR 所调用 peak 区域内的比对片段占全部比对片段的比例计算得到。详见 <a href='https://www.encodeproject.org/data-standards/terms/' target='_blank'>FRiP 得分</a>。",
    ),
    (
        "Calculated from the total number of overlapping peaks within group replicate sets",
        "由组内重复样本之间重叠 peak 的总数计算得到。",
    ),
]

SENTINEL = "\x00MASKEDZH\x00"


def _replace(html: str, en: str, zh: str) -> tuple[str, int, int]:
    """Replace free (untranslated) occurrences of en with zh, idempotently.

    Returns (new_html, replaced_count, free_count_before). The Chinese
    replacements embed the English original in parentheses, so the English
    string also occurs inside already-translated text: mask the existing
    Chinese strings first, replace on the masked copy, then restore.
    """
    free = html.count(en) - html.count(zh)
    if free <= 0:
        return html, 0, free
    masked = html.replace(zh, SENTINEL)
    hits = masked.count(en)
    if hits != free:
        raise ValueError(
            f"occurrence mismatch for {en!r}: free={free} but masked count={hits}"
        )
    out = masked.replace(en, zh).replace(SENTINEL, zh)
    return out, hits, free


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("report", help="path to the zh-Cutandrun multiqc_report.html")
    parser.add_argument("--dry-run", action="store_true", help="check only; do not write")
    args = parser.parse_args()

    try:
        with open(args.report, encoding="utf-8") as f:
            html = f.read()
    except OSError as e:
        print(f"error: cannot read {args.report}: {e}", file=sys.stderr)
        return 2

    if ZH_MARKER not in html:
        print(
            "error: report is not the zh_CN variant (missing Chinese title "
            f"{ZH_MARKER!r}). The English report is intentionally never modified; "
            "refusing to proceed.",
            file=sys.stderr,
        )
        return 2

    try:
        for en, zh in REQUIRED:
            html, hits, _ = _replace(html, en, zh)
            print(f"{'replaced' if hits else 'already  '} x{hits}: {en[:64]}")
        for en, zh in OPTIONAL:
            html, hits, free = _replace(html, en, zh)
            if hits:
                print(f"replaced   x{hits}: {en[:64]}")
            elif free == 0 and html.count(zh) == 0:
                print(f"absent     x0:  {en[:64]} (work-only input not on data face — skipping)")
            else:
                print(f"already    x0:  {en[:64]}")
    except ValueError as e:
        print(f"error: {e}", file=sys.stderr)
        return 1

    # Fail loud if a required string exists in neither form (layout change).
    for en, zh in REQUIRED:
        if en not in html and zh not in html:
            print(
                f"error: required string {en!r} missing from report in any form — "
                "the report layout changed (MultiQC version or section renames?). "
                "Nothing written.",
                file=sys.stderr,
            )
            return 1

    if args.dry_run:
        print("\ndry-run: all required strings found; no file written.")
        return 0

    with open(args.report, "w", encoding="utf-8") as f:
        f.write(html)
    print(f"\nwrote {args.report} (Peak QC child titles translated).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
