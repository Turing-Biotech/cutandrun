def load_terms() -> dict:
    """Tiny YAML-subset reader for the pinned terms file (single source)."""
    if not os.path.isfile(TERMS):
        return {}
    out: dict = {}
    stack: list[tuple[int, str]] = []
    cur: dict = out
    for raw in open(TERMS, encoding="utf-8").read().splitlines():
        line = raw.rstrip()
        if not line.strip() or line.strip().startswith("#"):
            continue
        indent = len(line) - len(line.lstrip())
        key, _, rest = line.strip().partition(":")
        rest = rest.strip()
        while stack and stack[-1][0] >= indent:
            stack.pop()
        cur = out
        for _, k in stack:
            cur = cur.setdefault(k, {})
        if rest:
            cur[key.strip()] = rest.strip('"\'')
        else:
            cur[key.strip()] = {}
            stack.append((indent, key.strip()))
    return out


