def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--vendor-dir", required=True)
    ap.add_argument("--outdir", required=True)
    ap.add_argument("--multiqc-html", default=None,
                    help="path to the zh multiqc_report.html to copy into outdir/multiqc/")
    ap.add_argument("--flow-png", default=None,
                    help="path to the 8-module flow diagram PNG (default: script dir's pipeline_8modules.png)")
    ap.add_argument("--run-root", default=None,
                    help="published run output/ tree for --cross-check")
    ap.add_argument("--cross-check", action="store_true")
    ap.add_argument("--verify-only", action="store_true",
                    help="skip fusion; run the coverage checklist on --outdir")
    ap.add_argument("--no-verify", action="store_true")
    args = ap.parse_args()

    log: list[str] = [f"fuse_report_zh  {datetime.now(timezone.utc).isoformat(timespec='seconds')}\n{'=' * 60}"]

    if args.verify_only:
        log.append("verify-only mode")
        return verify(args.outdir, log)

    vendor = args.vendor_dir
    outdir = args.outdir
    html_path = os.path.join(vendor, "report.html")
    if not os.path.isfile(html_path):
        print(f"error: {html_path} missing", file=sys.stderr)
        return 2
    html = open(html_path, encoding="utf-8").read()

    # outdir: fresh report/ (keep any pre-existing outdir contents other than
    # what we generate — but default to clean for idempotency)
    os.makedirs(outdir, exist_ok=True)

    terms = load_terms()
    html, edits, cross = fuse(html, terms, args, log)

    copy_assets(vendor, outdir, log)

    # flow png
    flow = args.flow_png or os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                         "pipeline_8modules.png")
    os.makedirs(os.path.join(outdir, "imgExtra"), exist_ok=True)
    if os.path.isfile(flow):
        shutil.copy2(flow, os.path.join(outdir, "imgExtra", "pipeline_8modules.png"))
        log.append("ok    imgExtra/pipeline_8modules.png copied")
    else:
        log.append(f"MISS  flow png {flow} — 流程图引用将悬空")

    # multiqc report
    if args.multiqc_html:
        mqc_d = os.path.join(outdir, "multiqc")
        os.makedirs(mqc_d, exist_ok=True)
        shutil.copy2(args.multiqc_html, os.path.join(mqc_d, "multiqc_report.html"))
        base = os.path.basename(args.multiqc_html)
        dstem = os.path.splitext(base)[0].replace("multiqc_report", "multiqc_report")
        # copy sibling data/plots dirs if present
        src_d = os.path.dirname(args.multiqc_html)
        for sib in glob.glob(os.path.join(src_d, "*_report_data")) + \
                   glob.glob(os.path.join(src_d, "*_report_plots")):
            if os.path.isdir(sib):
                shutil.copytree(sib, os.path.join(mqc_d, os.path.basename(sib)),
                                dirs_exist_ok=True)
        log.append("ok    multiqc/ copied (zh report + data + plots)")
    else:
        log.append("warn  no --multiqc-html: iframe will 404 (run T2d first)")

    # cross-check artifact (machine-readable, sits with the registry)
    if args.cross_check:
        cc_path = os.path.join(outdir, "crosscheck.json")
        with open(cc_path, "w", encoding="utf-8") as f:
            json.dump(cross, f, ensure_ascii=False, indent=2)
        log.append(f"ok    crosscheck.json -> {cc_path}")

    with open(os.path.join(outdir, "report.html"), "w", encoding="utf-8") as f:
        f.write(html)
    log.append("ok    report.html written")

    rc = 0
    if not args.no_verify:
        log.append("\n--- verify ---")
        rc = verify(outdir, log)

    print("\n".join(log))
    return rc


if __name__ == "__main__":
    sys.exit(main())
