def _table_cells(seg: str) -> list[list[str]]:
    rows = re.findall(r"<tr[^>]*>(.*?)</tr>", seg, re.S)
    out = []
    for r in rows:
        cells = re.findall(r"<t[dh][^>]*>(.*?)</t[dh]>", r, re.S)
        out.append([re.sub(r"<[^>]+>", "", c).strip() for c in cells])
    return out


def extract_vendor_tables(html: str) -> dict:
    """Vendor T6/T7 are WIDE tables (samples as columns):
      T6 head = [Sample, C1..E3] then rows All/UnMapped/Mapped/MappedRate(%)/...
      T7 head = [Sample, C1..E3] then row Peaknum.
    We pull the MappedRate(%) row and the Peaknum row directly."""
    tabs = [(m.start(), m.end()) for m in re.finditer(r"<table\b.*?</table>", html, re.S)]
    res: dict = {}
    for s, e in tabs:
        rows = _table_cells(html[s:e])
        if not rows or len(rows[0]) < 2:
            continue
        head = rows[0]
        if head[0] != "Sample":
            continue
        samples = head[1:]
        # T6: has a MappedRate(%) row
        for r in rows:
            if r and r[0] == "MappedRate(%)":
                res["align"] = {s_: r[i + 1] for i, s_ in enumerate(samples)}
        # T7: has a Peaknum row
        for r in rows:
            if r and r[0] == "Peaknum":
                res["peak"] = {s_: r[i + 1] for i, s_ in enumerate(samples)}
    return res


