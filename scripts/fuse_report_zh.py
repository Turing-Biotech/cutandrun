def run_side_numbers(run_root: str | None) -> dict:
    """Read the published run's own numbers: bed line counts (peaks) and
    bowtie2 overall alignment rates. rid keys = sample id (C_R1, E_R2, ...)."""
    if not run_root or not os.path.isdir(run_root):
        return {}
    out: dict = {"peak": {}, "align": {}}
    # peak counts: published narrowPeak / stringent beds
    for d in ("macs2", "seacr"):
        pat = os.path.join(run_root, "03_peak_calling/04_called_peaks", d, "*")
        for bed in sorted(glob.glob(pat)):
            base = os.path.basename(bed)
            if base.endswith(".md5") or base.endswith(".xls"):
                continue
            rid = base.split(".")[0]
            n = sum(1 for _ in open(bed, errors="replace"))
            out["peak"].setdefault(rid, {})[d] = n
    out["consensus"] = {}
    cons = os.path.join(run_root, "03_peak_calling/05_consensus_peaks")
    for bed in sorted(glob.glob(os.path.join(cons, "*.consensus.peaks.awk.bed"))):
        if bed.endswith(".md5"):
            continue
        out["consensus"] = sum(1 for _ in open(bed, errors="replace"))
    # bowtie2 alignment rates: 02_alignment/bowtie2/{target,spikein}/log/<rid>...bowtie2.log
    for d in ("target", "spikein"):
        pat = os.path.join(run_root, "02_alignment/bowtie2", d, "log", "*.log")
        for lg in sorted(glob.glob(pat)):
            m = re.search(r"([0-9.]+)% overall alignment rate",
                          open(lg, errors="replace").read())
            if m:
                rid = os.path.basename(lg).split(".bowtie2.log")[0]
                out["align"].setdefault(rid, {})[d] = float(m.group(1))
    return out


def _num(x) -> str:
    return f"{x:,}" if isinstance(x, (int, float)) else str(x)


def build_crosscheck_rows(v: dict, r: dict) -> dict:
    """Assemble side-by-side 口径 tables (never reconcile across pipelines).
    v = {align: {sample: '97.01' (str %)}, peak: {sample: '626'}}
    r = {peak: {sample: {macs2: n, seacr: n}}, align: {sample: {target: f, spikein: f}},
         consensus: n}"""
    rows: dict = {}
    # vendor column C1/E3 → pipeline rid C_R1/E_R3
    v2r = {s: s[:1] + "_R" + s[1:] if re.fullmatch(r"[CE]\d", s) else s
           for s in v.get("align", {})}
    samples = list(v.get("align", {}).keys())  # vendor column order (C1..E3)

    # alignment rate table: sample | vendor 比对率% | 本管线 bowtie2%(target)
    al = v.get("align")
    if al and r.get("align"):
        body = []
        for s in samples:
            rend = v2r[s]
            vend = al.get(s, "—")
            run = r["align"].get(rend, {}).get("target")
            body.append([s,
                         f"{float(vend):.2f}%" if vend not in (None, "—", "") else "—",
                         f"{run:.2f}%" if run is not None else "—"])
        rows["align"] = {
            "head": ["样本", "参考报告比对率（MappedRate, vendor BWA 流程）",
                     "本管线 Bowtie2 比对率（target 基因组）"],
            "body": body,
            "note": ("参考报告采 vendor 流程（BWA 比对，Single-end/双端按其流程）；"
                     "本管线列为 Bowtie2 对目标基因组（mm39）的实际比对率。"
                     "两者比对软件与流程不同，数字并列展示、不互相覆盖，仅用于量级口径核对。"),
        }

    # peak count table
    pk = v.get("peak")
    if pk and r.get("peak"):
        body = []
        for s in samples:
            m = r["peak"].get(v2r[s], {})
            body.append([s, _num(pk.get(s, "—")),
                         _num(m["macs2"]) if "macs2" in m else "—",
                         _num(m["seacr"]) if "seacr" in m else "—"])
        cnum = r.get("consensus")
        rows["peak"] = {
            "head": ["样本", "参考报告 Peak 数", "本管线 MACS2（narrowPeak 行数）",
                     "本管线 SEACR（stringent 行数）"],
            "body": body,
            "note": (f"本管线发布 consensus（SEACR 交集，E 组）共 "
                     f"{_num(cnum) if cnum else '—'} 个。"
                     "参考报告 Peak 数来自 vendor 流程（BWA 比对 + 其 peak 参数）；"
                     "本管列为 MACS2 与 SEACR 对该运行各自调用的 narrowPeak 行数。"
                "本管线按 nf-core/cutandrun 默认只对样本（E 组）调 peak，"
                "C 组（对照）不出 peak，故对应行为「—」。"
                     "两组调用参数不同，绝对量级与排序不直接可比，并列展示仅用于口径核对；"
                     "MACS2 行数通常高于 SEACR stringent 属正常（后者更严格）。"),
        }
    return rows


