def verify(outdir: str, log: list) -> int:
    html_path = os.path.join(outdir, "report.html")
    html = open(html_path, encoding="utf-8").read()
    failures = []

    def check(label: str, cond: bool, detail: str = ""):
        log.append(f"{'PASS  ' if cond else 'FAIL  '} {label}{(' — ' + detail) if detail else ''}")
        if not cond:
            failures.append(label)

    heads = re.findall(r"<(h[1-4])\b", html)
    check("headings >= 38 (vendor 39 - appendix 3 + 1 MultiQC Section)", len(heads) >= 38, f"got {len(heads)}")
    check("appendix removed (附录 h1 gone)", not re.search(r'<h1[^>]*>\s*附录\s*</h1>', html))
    check("appendix brand blocks gone (公众号)", "公众号" not in html)
    check("MultiQC Section present", "标准分析 Section 1.5-质控交互报告（MultiQC 中文版）" in html)
    check("iframe present", "multiqc/multiqc_report.html" in html and "<iframe" in html)
    check("brand 嘉因 == 0", "嘉因" not in html)
    check("brand 图凌 present", "图凌生物" in html)
    check("jiayin refs == 0", "jiayin" not in html.lower())
    check("rainbow refs == 0", "rainbow-genome" not in html)
    check("BWA method wording == 0 (bwa program)", "using the bwa program" not in html)
    check("vendor weixin links == 0", "mp.weixin.qq.com" not in html)
    check("Bowtie2 method present", "本次分析采用 Bowtie2 比对软件" in html)
    check("bowtie2 en sentence present", "using the bowtie2 program" in html)

    tables = len(re.findall(r"<table\b", html))
    check(f"tables >= 28 (vendor 28 + cross-check blocks)", tables >= 28, f"got {tables}")

    img_refs = sorted(set(re.findall(r'<img\b[^>]*src="([^"]+)"', html)))
    missing = [r for r in img_refs
               if not os.path.isfile(os.path.join(outdir, r.lstrip("./")))]
    check("all img refs resolve", not missing, str(missing))

    badges = len(re.findall(r'class="fig-badge">示例图', html))
    check("placeholder badges == 8", badges == 8, f"got {badges}")

    check("8-module flow fig referenced", "./imgExtra/pipeline_8modules.png" in html)
    check("vendor 21-stage kept as 交付全流程", 'class="fig-badge">交付全流程' in html)

    mqc_html = os.path.join(outdir, "multiqc", "multiqc_report.html")
    if os.path.isfile(mqc_html):
        m = open(mqc_html, encoding="utf-8").read()
        check("multiqc zh title", "CUT&RUN/CUT&TAG 质控报告（MultiQC 简体中文版）" in m)
        check("multiqc peak qc zh", "样本 Peak 数量（Sample Peak Count）" in m)
        check("multiqc no tofu", "\ufffd" not in m)
    else:
        check("multiqc report copied", False, mqc_html + " missing")

    # assets
    for d in ("css", "js", "imgHeader", "imgTail"):
        check(f"asset dir {d}/", os.path.isdir(os.path.join(outdir, d)))

    log.append("\nverify: " + ("ALL PASS" if not failures else f"FAILURES: {failures}"))
    return 1 if failures else 0


